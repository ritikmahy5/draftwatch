#!/usr/bin/env python3
"""Builds one model family's fine-tuning data (docs/EVALUATION.md, "Fine-tuning runs").

  build_training_data.py select --model <target dir> --probes <probe dir> --out <data dir>
      CPU. Draws disjoint UltraChat first turns for the trunk and the branch. Writes
      trunk-prompts.jsonl and branch-prompts.jsonl (all candidates), and branch.jsonl: 19,200
      (prompt, first UltraChat reply) pairs that fit the length limits under the target's
      tokenizer.

  build_training_data.py generate --model <generating model> --data <data dir> --prompts trunk
      GPU, vLLM. Greedy responses (up to 768 new tokens, no speculative decoding) to the trunk
      candidates; keeps those that ended on their own and fit the limits; writes trunk.jsonl
      (38,400 examples). With --prompts branch and --tokenizer <this family's target>, it answers
      the branch candidates with another family's target instead and writes branch-cross.jsonl
      (19,200 examples), P4's last fallback.

Every output is recorded in data.sha256.json. The generated responses cannot be regenerated byte
for byte, so the data directory is archived with the results.
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from draftwatch_eval.manifest import write_files  # noqa: E402
from draftwatch_eval.training_data import (  # noqa: E402
    disjoint_split, first_turns, keep, prompt_lines, take, token_counts)

ULTRACHAT = ("HuggingFaceH4/ultrachat_200k", "8049631c405ae6576f93f445c6b8166f76f5505a",
             "train_sft")
PROBE_FILES = ("chat.jsonl", "chat-live.jsonl", "code.jsonl", "code-live.jsonl")
TRUNK_EXAMPLES = 1200 * 32
BRANCH_EXAMPLES = 600 * 32
TRUNK_CANDIDATES = 48000
BRANCH_CANDIDATES = 24000
MAX_NEW_TOKENS = 768
SEED = 0
MANIFEST = "data.sha256.json"


def _lines(records):
    return "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in records).encode("utf-8")


def _read(path):
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]


def _tokenizer(path):
    from transformers import AutoTokenizer

    return AutoTokenizer.from_pretrained(path)


def select(args):
    from datasets import load_dataset

    name, revision, split = ULTRACHAT
    turns, skipped = first_turns(load_dataset(name, split=split, revision=revision))
    probes = []
    for f in PROBE_FILES:
        probes.extend(prompt_lines((args.probes / f).read_bytes()))
    trunk, branch = disjoint_split(turns, probes, TRUNK_CANDIDATES, BRANCH_CANDIDATES, SEED)
    tokenizer = _tokenizer(args.model)

    def fits(t):
        response, total = token_counts(tokenizer, t.prompt, t.reply)
        return keep(response, total, True)  # UltraChat replies are complete

    branch_kept = take((t for t in branch if fits(t)), BRANCH_EXAMPLES, "branch examples")
    hashes = write_files(args.out, {
        "trunk-prompts.jsonl": _lines({"id": t.prompt_id, "prompt": t.prompt} for t in trunk),
        "branch-prompts.jsonl": _lines({"id": t.prompt_id, "prompt": t.prompt} for t in branch),
        "branch.jsonl": _lines({"id": t.prompt_id, "prompt": t.prompt, "response": t.reply}
                               for t in branch_kept),
    }, MANIFEST)
    print("skipped %d conversations without a first user/assistant turn" % skipped)
    return hashes


def generate(args):
    # vLLM v0.31.0: LLM.chat(messages, sampling_params, use_tqdm) takes a list of conversations
    # (vllm/entrypoints/llm.py:615); CompletionOutput.finish_reason is "stop" when the model
    # ended the response and "length" at max_tokens (vllm/outputs.py:65).
    from vllm import LLM, SamplingParams

    source, out_name, needed = {
        "trunk": ("trunk-prompts.jsonl", "trunk.jsonl", TRUNK_EXAMPLES),
        "branch": ("branch-prompts.jsonl", "branch-cross.jsonl", BRANCH_EXAMPLES),
    }[args.prompts]
    candidates = _read(args.data / source)
    llm = LLM(model=str(args.model), dtype="bfloat16", seed=SEED)
    outputs = llm.chat(
        [[{"role": "user", "content": c["prompt"]}] for c in candidates],
        SamplingParams(temperature=0, max_tokens=MAX_NEW_TOKENS),
    )
    tokenizer = _tokenizer(args.tokenizer or args.model)

    def kept():
        for c, out in zip(candidates, outputs):
            completion = out.outputs[0]
            response, total = token_counts(tokenizer, c["prompt"], completion.text)
            if keep(response, total, completion.finish_reason == "stop"):
                yield {"id": c["id"], "prompt": c["prompt"], "response": completion.text}

    examples = take(kept(), needed, "%s examples" % args.prompts)
    return write_files(args.data, {out_name: _lines(examples)}, MANIFEST)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    s = sub.add_parser("select", help="draw the trunk and branch data (CPU)")
    s.add_argument("--model", required=True, type=Path, help="this family's target")
    s.add_argument("--probes", required=True, type=Path, help="directory of the probe files")
    s.add_argument("--out", required=True, type=Path, help="this family's data directory")
    g = sub.add_parser("generate", help="generate greedy responses (GPU)")
    g.add_argument("--model", required=True, type=Path, help="the model that answers")
    g.add_argument("--data", required=True, type=Path, help="this family's data directory")
    g.add_argument("--prompts", required=True, choices=("trunk", "branch"))
    g.add_argument("--tokenizer", type=Path,
                   help="this family's target, when --model is another family's (default: --model)")
    args = parser.parse_args(argv)
    hashes = select(args) if args.command == "select" else generate(args)
    for name in sorted(hashes):
        print("%s  %s" % (hashes[name], name))
    return 0


if __name__ == "__main__":
    sys.exit(main())
